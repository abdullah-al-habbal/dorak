use Modules\Dashboard\Http\Actions\Stylists\ListStylistsAction;
use Modules\Dashboard\Http\Actions\Stylists\ShowStylistAction;
use Modules\Dashboard\Http\Actions\Stylists\StoreStylistAction;
use Modules\Dashboard\Http\Actions\Stylists\UpdateStylistAction;
use Modules\Dashboard\Http\Middleware\DashboardAuthorizationMiddleware;
use Modules\Dashboard\Http\Middleware\DashboardOperationsAuthorizationMiddleware;
use Modules\Preference\Http\Middleware\ApplyPreferredLocaleMiddleware;

// Branch operations routes for managers, owners and the admin.
Route::prefix('dashboard')->group(function (): void {
    Route::middleware([DashboardAuthorizationMiddleware::class, DashboardOperationsAuthorizationMiddleware::class, ApplyPreferredLocaleMiddleware::class])->group(function (): void {
        Route::get('/overview', OverviewAction::class);
        Route::get('/bookings', ListBookingsAction::class);
        Route::post('/bookings/walk-in', CreateWalkInBookingAction::class);
        Route::get('/bookings/{booking}', ShowBookingAction::class);
        Route::get('/bookings/{booking}/history', ShowBookingHistoryAction::class);
        Route::patch('/bookings/{booking}', UpdateBookingStatusAction::class);
        Route::patch('/bookings/{booking}/cancel', CancelBookingAction::class);
        Route::patch('/bookings/{booking}/reschedule', RescheduleBookingAction::class);
        Route::post('/bookings/{booking}/review', ReviewBookingClientAction::class);
        Route::get('/branches', ListBranchesAction::class);
        Route::get('/branches/{branch}', ShowBranchAction::class);
        Route::post('/branches', StoreBranchAction::class);
        Route::put('/branches/{branch}', UpdateBranchAction::class);
        Route::delete('/branches/{branch}', DestroyBranchAction::class);
        Route::get('/branches/{branch}/opening-hours', ShowBranchOpeningHoursAction::class);
        Route::put('/branches/{branch}/opening-hours', UpdateBranchOpeningHoursAction::class);
        Route::get('/branches/{branch}/hours-overrides', ListBranchHoursOverridesAction::class);
        Route::put('/branches/{branch}/hours-overrides', SetBranchHoursOverrideRangeAction::class);
        Route::put('/branches/{branch}/hours-overrides/{date}', SetBranchHoursOverrideAction::class)->where('date', '\\d{4}-\\d{2}-\\d{2}');
        Route::delete('/branches/{branch}/hours-overrides/{date}', ClearBranchHoursOverrideAction::class)->where('date', '\\d{4}-\\d{2}-\\d{2}');
        Route::get('/branches/{branch}/floor-plan', ShowBranchFloorPlanAction::class);
        Route::patch('/branches/{branch}/floor-plan', UpdateBranchFloorPlanAction::class);
        Route::get('/branches/{branch}/reviews', ListBranchReviewsAction::class);
        Route::post('/branches/{branch}/reviews/{review}/dispute', FlagBranchReviewDisputeAction::class)->whereUuid('review');
        Route::get('/barber-lookup', LookupBarbersAction::class)->middleware('throttle:'.DashboardBarberLookupConstants::BARBER_LOOKUP_LIMITER);
        Route::get('/branches/{branch}/affiliations', ListBranchAffiliationsAction::class);
        Route::post('/branches/{branch}/affiliations', InviteBranchAffiliationAction::class);
        Route::post('/branches/{branch}/affiliations/by-contact', InviteBranchAffiliationByContactAction::class)->middleware('throttle:'.DashboardBarberLookupConstants::BARBER_LOOKUP_LIMITER);
        Route::post('/branches/{branch}/affiliations/{affiliation}/accept', RespondBranchAffiliationAction::class)->defaults('accept', true);
        Route::post('/branches/{branch}/affiliations/{affiliation}/reject', RespondBranchAffiliationAction::class)->defaults('accept', false);
        Route::post('/branches/{branch}/affiliations/{affiliation}/terminate', TerminateBranchAffiliationAction::class);
        Route::get('/branches/{branch}/job-postings', ListBranchJobPostingsAction::class);
        Route::post('/branches/{branch}/job-postings', StoreBranchJobPostingAction::class);
        Route::put('/branches/{branch}/job-postings/{jobPosting}', UpdateBranchJobPostingAction::class);
        Route::delete('/branches/{branch}/job-postings/{jobPosting}', DestroyBranchJobPostingAction::class);
        Route::get('/branches/{branch}/job-postings/{jobPosting}/applications', ListBranchApplicationsAction::class);
        Route::post('/branches/{branch}/job-postings/{jobPosting}/applications/mark-seen', MarkBranchApplicationsSeenAction::class);
        Route::patch('/branches/{branch}/job-postings/{jobPosting}/applications/{application}/status', UpdateBranchApplicationStatusAction::class);
        Route::get('/services', ListServicesAction::class);
        Route::post('/services', StoreServiceAction::class);
        Route::get('/services/{service}', ShowServiceAction::class);
        Route::put('/services/{service}', UpdateServiceAction::class);
        Route::delete('/services/{service}', DestroyServiceAction::class);
        Route::get('/currencies', ListCurrenciesAction::class);
        Route::get('/service-categories', ListServiceCategoriesAction::class);
        Route::post('/service-categories', StoreServiceCategoryAction::class);
        Route::get('/chairs', ListChairsAction::class);
        Route::post('/chairs', StoreChairAction::class);
        Route::get('/chairs/{chair}', ShowChairAction::class);
        Route::put('/chairs/{chair}', UpdateChairAction::class);
        Route::delete('/chairs/{chair}', DestroyChairAction::class);
        Route::get('/stylists', ListStylistsAction::class);
        Route::post('/stylists', StoreStylistAction::class);
        Route::get('/stylists/{stylist}', ShowStylistAction::class);
        Route::put('/stylists/{stylist}', UpdateStylistAction::class);
        Route::delete('/stylists/{stylist}', DestroyStylistAction::class);
        Route::patch('/stylists/{stylist}/activate', ActivateStylistAction::class);
        Route::patch('/stylists/{stylist}/deactivate', DeactivateStylistAction::class);
    });
});
